const fn cs_type(ty: Type) -> &'static str {
    match ty {
        Type::Bool => "bool",
        Type::I32 => "int",
        Type::U32 => "uint",
        Type::I64 => "long",
        Type::U64 => "ulong",
        Type::F64 => "double",
        Type::String => "string",
    }
}

/// The P/Invoke type of an argument.
const fn cs_native(ty: Type) -> &'static str {
    match ty {
        Type::Bool => "byte",
        Type::String => "byte[]",
        other => cs_type(other),
    }
}

/// The P/Invoke type of a result or callback argument.
const fn cs_native_out(ty: Type) -> &'static str {
    match ty {
        Type::Bool => "byte",
        Type::String => "IntPtr",
        other => cs_type(other),
    }
}

fn cs_argument(param: &Param) -> String {
    match param.ty {
        Type::Bool => format!("(byte)({} ? 1 : 0)", param.name),
        Type::String => format!("Native.Utf8Z({})", param.name),
        _ => param.name.clone(),
    }
}

fn cs_doc(out: &mut String, doc: &[String], indent: &str) {
    if doc.is_empty() {
        return;
    }
    let _ = writeln!(out, "{indent}/// <summary>{}</summary>", doc.join(" "));
}

/// The C# bindings.
#[must_use]
pub fn csharp(idl: &Idl) -> String {
    let library = &idl.library;
    let mut out = String::new();
    let _ = writeln!(out, "// Generated by rustnative-interop from `{library}.ril`. Do not edit.");
    let _ = writeln!(
        out,
        "using System;\nusing System.Collections.Generic;\nusing System.Runtime.InteropServices;\nusing System.Text;\n"
    );
    let _ = writeln!(out, "namespace {}.Interop\n{{", pascal(library));
    let _ = writeln!(
        out,
        "    /// <summary>A failure the library reported, with its status code.</summary>\n    public sealed class InteropException : Exception\n    {{\n        private readonly int status;\n        public InteropException(int status, string message) : base(message) {{ this.status = status; }}\n        public int Status {{ get {{ return status; }} }}\n    }}\n"
    );
    // Native declarations.
    let _ = writeln!(
        out,
        "    internal static class Native\n    {{\n        private const string Library = \"{library}\";\n"
    );
    let import = "        [DllImport(Library, CallingConvention = CallingConvention.Cdecl)]";
    let _ =
        writeln!(out, "{import}\n        internal static extern IntPtr {library}_last_error();");
    let _ = writeln!(
        out,
        "{import}\n        internal static extern void {library}_string_free(IntPtr value);"
    );
    for service in &idl.services {
        let mut params: Vec<String> = service
            .constructor
            .iter()
            .map(|param| format!("{} {}", cs_native(param.ty), param.name))
            .collect();
        params.push("out ulong handle".to_owned());
        let _ = writeln!(
            out,
            "{import}\n        internal static extern int {}({});",
            symbol(idl, service, "new"),
            params.join(", ")
        );
        let _ = writeln!(
            out,
            "{import}\n        internal static extern int {}(ulong self);",
            symbol(idl, service, "free")
        );
        for method in &service.methods {
            let mut params = vec!["ulong self".to_owned()];
            params.extend(
                method.params.iter().map(|param| format!("{} {}", cs_native(param.ty), param.name)),
            );
            if let Some(ty) = method.returns {
                params.push(format!("out {} result", cs_native_out(ty)));
            }
            let _ = writeln!(
                out,
                "{import}\n        internal static extern int {}({});",
                symbol(idl, service, &method.name),
                params.join(", ")
            );
        }
        for event in &service.events {
            let _ = writeln!(
                out,
                "{import}\n        internal static extern int {}(ulong self, {}{}Fn callback, IntPtr context);",
                symbol(idl, service, &format!("on_{}", event.name)),
                service.name,
                pascal(&event.name)
            );
        }
    }
    let _ = writeln!(
        out,
        r#"
        internal static void Check(int status)
        {{
            if (status != 0) throw new InteropException(status, Utf8({library}_last_error()));
        }}

        internal static byte[] Utf8Z(string value)
        {{
            if (value == null) throw new ArgumentNullException("value");
            byte[] bytes = Encoding.UTF8.GetBytes(value);
            byte[] terminated = new byte[bytes.Length + 1];
            Array.Copy(bytes, terminated, bytes.Length);
            return terminated;
        }}

        internal static string Utf8(IntPtr pointer)
        {{
            if (pointer == IntPtr.Zero) return "";
            int length = 0;
            while (Marshal.ReadByte(pointer, length) != 0) length++;
            byte[] bytes = new byte[length];
            Marshal.Copy(pointer, bytes, 0, length);
            return Encoding.UTF8.GetString(bytes);
        }}

        internal static string TakeUtf8(IntPtr pointer)
        {{
            try {{ return Utf8(pointer); }} finally {{ {library}_string_free(pointer); }}
        }}
    }}
"#
    );
    for service in &idl.services {
        csharp_class(&mut out, idl, service);
    }
    let _ = writeln!(out, "}}");
    out
}

