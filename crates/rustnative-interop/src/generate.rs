//! Bindings generated from an [`Idl`] — never written by hand per language
//! (`PLAN.md` Milestone 40, concept `C66`).
//!
//! - [`c`]: the C header a host includes;
//! - [`csharp`]: P/Invoke bindings (C# 5, so the .NET Framework compiler
//!   every Windows machine has can build them) with an `IDisposable`
//!   wrapper per service;
//! - [`rust`]: the implementation side — a trait per service, its events,
//!   and an `export_<library>!` macro that writes the `extern "C"` shims
//!   over [`crate::runtime`] (handle table, panic containment, thread
//!   check).
//!
//! The C ABI they share: every function returns an `int32_t` status (see
//! [`crate::runtime::status`]) and writes its result through a final
//! out-pointer; a service instance is a `uint64_t` handle the host frees;
//! a `string` argument is borrowed for the call and a returned one is the
//! host's to free with `<library>_string_free`.

use std::fmt::Write as _;

use crate::idl::{Idl, Param, Receiver, Service, Threading, Type};

fn pascal(name: &str) -> String {
    name.split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            chars
                .next()
                .map(|first| first.to_ascii_uppercase().to_string() + chars.as_str())
                .unwrap_or_default()
        })
        .collect()
}

/// Whether every method of `service` is owner-affine.
fn owner_only(service: &Service) -> bool {
    service.methods.iter().all(|method| method.threading == Threading::Owner)
}

fn symbol(idl: &Idl, service: &Service, name: &str) -> String {
    format!("{}_{}_{name}", idl.library, service.name)
}

