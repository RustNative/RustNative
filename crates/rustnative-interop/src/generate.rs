// ---------------------------------------------------------------------------

const fn rust_type(ty: Type) -> &'static str {
    match ty {
        Type::Bool => "bool",
        Type::I32 => "i32",
        Type::U32 => "u32",
        Type::I64 => "i64",
        Type::U64 => "u64",
        Type::F64 => "f64",
        Type::String => "&str",
    }
}

const fn rust_ffi(ty: Type) -> &'static str {
    match ty {
        Type::Bool => "u8",
        Type::String => "*const ::core::ffi::c_char",
        other => rust_type(other),
    }
}

const fn rust_ffi_out(ty: Type) -> &'static str {
    match ty {
        Type::Bool => "*mut u8",
        Type::I32 => "*mut i32",
        Type::U32 => "*mut u32",
        Type::I64 => "*mut i64",
        Type::U64 => "*mut u64",
        Type::F64 => "*mut f64",
        Type::String => "*mut *mut ::core::ffi::c_char",
    }
}

const fn rust_return(ty: Type) -> &'static str {
    match ty {
        Type::String => "::std::string::String",
        other => rust_type(other),
    }
}

/// Converts FFI arguments to Rust ones at the top of a shim.
fn rust_prologue(params: &[Param]) -> String {
    let mut out = String::new();
    for param in params {
        let name = &param.name;
        match param.ty {
            Type::String => {
                let _ = writeln!(
                    out,
                    "                // SAFETY: the header's contract: a `string` argument is a NUL-terminated\n                // UTF-8 string valid for the call.\n                let {name} = unsafe {{ ::rustnative_interop::runtime::borrow_str({name}, \"{name}\") }}?;"
                );
            }
            Type::Bool => {
                let _ = writeln!(out, "                let {name} = {name} != 0;");
            }
            _ => {}
        }
    }
    out
}

fn rust_doc(out: &mut String, doc: &[String], indent: &str) {
    for line in doc {
        let _ = writeln!(out, "{indent}/// {line}");
    }
}

/// The implementation side: include it in the crate that implements the
/// library (`include!(concat!(env!("OUT_DIR"), "/<library>.rs"))`),
/// implement each service's trait, and call `export_<library>!` with the
/// implementing types in declaration order.
#[must_use]
pub fn rust(idl: &Idl) -> String {
    let library = &idl.library;
    let mut out = String::new();
    let _ =
        writeln!(out, "// Generated by rustnative-interop from `{library}.ril`. Do not edit.\n");
    for service in &idl.services {
        let name = &service.name;
        // Events.
        for event in &service.events {
            let mut params = vec!["*mut ::core::ffi::c_void".to_owned()];
            params.extend(event.params.iter().map(|param| rust_ffi(param.ty).to_owned()));
            let _ = writeln!(
                out,
                "/// The host's callback for `{name}`'s `{}` event.\npub type {name}{}Fn = unsafe extern \"C\" fn({});\n",
                event.name,
                pascal(&event.name),
                params.join(", ")
            );
        }
        let _ = writeln!(
            out,
            "/// The events a `{name}` raises, with the callbacks the host registered.\n#[derive(Default)]\npub struct {name}Events {{"
        );
        for event in &service.events {
            let _ = writeln!(
                out,
                "    {}: ::std::vec::Vec<({name}{}Fn, usize)>,",
                event.name,
                pascal(&event.name)
            );
        }
        let _ = writeln!(out, "}}\n\nimpl {name}Events {{");
        for event in &service.events {
            rust_doc(&mut out, &event.doc, "    ");
            let params: Vec<String> = event
                .params
                .iter()
                .map(|param| format!("{}: {}", param.name, rust_type(param.ty)))
                .collect();
            let mut conversions = String::new();
            let mut arguments = vec!["*context as *mut ::core::ffi::c_void".to_owned()];
            for param in &event.params {
                match param.ty {
                    Type::String => {
                        let _ = writeln!(
                            conversions,
                            "        let {0} = ::std::ffi::CString::new({0}.replace('\\0', \" \")).unwrap_or_default();",
                            param.name
                        );
                        arguments.push(format!("{}.as_ptr()", param.name));
                    }
                    Type::Bool => arguments.push(format!("u8::from({})", param.name)),
                    _ => arguments.push(param.name.clone()),
                }
            }
            let _ = writeln!(
                out,
                "    /// Raises `{event}`: calls every registered callback, on this thread.\n    pub fn {event}(&self{comma}{params}) {{\n{conversions}        for (callback, context) in &self.{event} {{\n            // SAFETY: the host registered `callback` with `context` for this event,\n            // and its contract keeps both valid until the instance is freed.\n            unsafe {{ callback({arguments}) }};\n        }}\n    }}",
                event = event.name,
                comma = if params.is_empty() { "" } else { ", " },
                params = params.join(", "),
                arguments = arguments.join(", ")
            );
        }
        let _ = writeln!(out, "}}\n");
        // The trait.
        rust_doc(&mut out, &service.doc, "");
        // A service reachable from any thread must be `Send`; one whose every
        // method is owner-affine need not be (it may hold a component tree).
        let bound = if owner_only(service) { "'static" } else { "Send + 'static" };
        let _ = writeln!(out, "pub trait {name}: {bound} {{");
        let params: Vec<String> = service
            .constructor
            .iter()
            .map(|param| format!("{}: {}", param.name, rust_type(param.ty)))
            .collect();
        let _ = writeln!(
            out,
            "    /// Creates an instance.\n    fn new({}) -> Self\n    where\n        Self: Sized;",
            params.join(", ")
        );
        for method in &service.methods {
            rust_doc(&mut out, &method.doc, "    ");
            let receiver = match method.receiver {
                Receiver::Shared => "&self",
                Receiver::Exclusive => "&mut self",
            };
            let mut params: Vec<String> = method
                .params
                .iter()
                .map(|param| format!("{}: {}", param.name, rust_type(param.ty)))
                .collect();
            if method.receiver == Receiver::Exclusive {
                params.push(format!("events: &{name}Events"));
            }
            let returns =
                method.returns.map(|ty| format!(" -> {}", rust_return(ty))).unwrap_or_default();
            let comma = if params.is_empty() { "" } else { ", " };
            let _ = writeln!(
                out,
                "    fn {}({receiver}{comma}{}){returns};",
                method.name,
                params.join(", ")
            );
        }
        let _ = writeln!(out, "}}\n");
        let _ = writeln!(
            out,
            "#[doc(hidden)]\npub struct {name}Instance<T> {{\n    pub value: T,\n    pub events: {name}Events,\n}}\n"
        );
    }
    // The export macro.
    let types: Vec<String> = idl
        .services
        .iter()
        .map(|service| format!("${}:ty", service.name.to_ascii_lowercase()))
        .collect();
    let _ = writeln!(
        out,
        "/// Exports the C interface of `{library}.ril`, implemented by the given\n/// types (one per service, in declaration order).\n#[allow(unused_macros)]\nmacro_rules! export_{library} {{\n    ({} $(,)?) => {{",
        types.join(", ")
    );
    let attributes = "        #[unsafe(no_mangle)]\n        #[allow(non_snake_case, clippy::must_use_candidate, clippy::missing_safety_doc)]";
    let _ = writeln!(
        out,
        "{attributes}\n        pub extern \"C\" fn {library}_last_error() -> *const ::core::ffi::c_char {{\n            ::rustnative_interop::runtime::last_error()\n        }}\n\n{attributes}\n        pub unsafe extern \"C\" fn {library}_string_free(value: *mut ::core::ffi::c_char) {{\n            // SAFETY: the header's contract: `value` is null or a string this library returned.\n            unsafe {{ ::rustnative_interop::runtime::free_string(value) }}\n        }}\n"
    );
    for service in &idl.services {
        rust_service_shims(&mut out, idl, service, attributes);
    }
    let _ = writeln!(out, "    }};\n}}");
    out
}

fn csharp_class(out: &mut String, idl: &Idl, service: &Service) {
    for event in &service.events {
        let mut params = vec!["IntPtr context".to_owned()];
        params.extend(
            event.params.iter().map(|param| format!("{} {}", cs_native_out(param.ty), param.name)),
        );
        let _ = writeln!(
            out,
            "    [UnmanagedFunctionPointer(CallingConvention.Cdecl)]\n    internal delegate void {}{}Fn({});\n",
            service.name,
            pascal(&event.name),
            params.join(", ")
        );
    }
    cs_doc(out, &service.doc, "    ");
    let name = &service.name;
    let _ = writeln!(out, "    public sealed class {name} : IDisposable\n    {{");
    let _ = writeln!(out, "        private ulong handle;");
    let _ =
        writeln!(out, "        // Delegates handed to native code, kept alive with the instance.");
    let _ = writeln!(
        out,
        "        private readonly List<Delegate> callbacks = new List<Delegate>();\n"
    );
    let params: Vec<String> = service
        .constructor
        .iter()
        .map(|param| format!("{} {}", cs_type(param.ty), param.name))
        .collect();
    let mut arguments: Vec<String> = service.constructor.iter().map(cs_argument).collect();
    arguments.push("out handle".to_owned());
    let _ = writeln!(
        out,
        "        public {name}({})\n        {{\n            Native.Check(Native.{}({}));\n        }}\n",
        params.join(", "),
        symbol(idl, service, "new"),
        arguments.join(", ")
    );
    for method in &service.methods {
        cs_doc(out, &method.doc, "        ");
        let params: Vec<String> = method
            .params
            .iter()
            .map(|param| format!("{} {}", cs_type(param.ty), param.name))
            .collect();
        let mut arguments = vec!["handle".to_owned()];
        arguments.extend(method.params.iter().map(cs_argument));
        let call = |arguments: &[String]| {
            format!("Native.{}({})", symbol(idl, service, &method.name), arguments.join(", "))
        };
        let body = match method.returns {
            None => format!("            Native.Check({});", call(&arguments)),
            Some(ty) => {
                arguments.push("out result".to_owned());
                let convert = match ty {
                    Type::Bool => "result != 0".to_owned(),
                    Type::String => "Native.TakeUtf8(result)".to_owned(),
                    _ => "result".to_owned(),
                };
                format!(
                    "            {} result;\n            Native.Check({});\n            return {convert};",
                    cs_native_out(ty),
                    call(&arguments)
                )
            }
        };
        let returns = method.returns.map_or("void", cs_type);
        let _ = writeln!(
            out,
            "        public {returns} {}({})\n        {{\n{body}\n        }}\n",
            pascal(&method.name),
            params.join(", ")
        );
    }
    for event in &service.events {
        let delegate = format!("{name}{}Fn", pascal(&event.name));
        let action = if event.params.is_empty() {
            "Action".to_owned()
        } else {
            format!(
                "Action<{}>",
                event.params.iter().map(|param| cs_type(param.ty)).collect::<Vec<_>>().join(", ")
            )
        };
        let lambda_params: Vec<String> = std::iter::once("context".to_owned())
            .chain(event.params.iter().map(|param| param.name.clone()))
            .collect();
        let forwarded: Vec<String> = event
            .params
            .iter()
            .map(|param| match param.ty {
                Type::Bool => format!("{} != 0", param.name),
                Type::String => format!("Native.Utf8({})", param.name),
                _ => param.name.clone(),
            })
            .collect();
        cs_doc(out, &event.doc, "        ");
        let _ = writeln!(
            out,
            "        public void On{}({action} handler)\n        {{\n            {delegate} callback = ({}) => handler({});\n            callbacks.Add(callback);\n            Native.Check(Native.{}(handle, callback, IntPtr.Zero));\n        }}\n",
            pascal(&event.name),
            lambda_params.join(", "),
            forwarded.join(", "),
            symbol(idl, service, &format!("on_{}", event.name))
        );
    }
    let _ = writeln!(
        out,
        "        public void Dispose()\n        {{\n            if (handle == 0) return;\n            Native.Check(Native.{}(handle));\n            handle = 0;\n        }}\n    }}\n",
        symbol(idl, service, "free")
    );
}

fn rust_service_shims(out: &mut String, idl: &Idl, service: &Service, attributes: &str) {
    let library = &idl.library;
    let name = &service.name;
    let ty = format!("${}", name.to_ascii_lowercase());
    let table = format!("{}_{}_INSTANCES", library.to_ascii_uppercase(), name.to_ascii_uppercase());
    let kind = if owner_only(service) { "OwnerTable" } else { "HandleTable" };
    let _ = writeln!(
        out,
        "        static {table}: ::rustnative_interop::runtime::{kind}<{name}Instance<{ty}>> =\n            ::rustnative_interop::runtime::{kind}::new();\n"
    );
    // Constructor.
    let mut params: Vec<String> = service
        .constructor
        .iter()
        .map(|param| format!("{}: {}", param.name, rust_ffi(param.ty)))
        .collect();
    params.push("out: *mut u64".to_owned());
    let arguments: Vec<&str> =
        service.constructor.iter().map(|param| param.name.as_str()).collect();
    let _ = writeln!(
        out,
        "{attributes}\n        pub unsafe extern \"C\" fn {}({}) -> i32 {{\n            ::rustnative_interop::runtime::guard(|| {{\n{}                let value = <{ty} as {name}>::new({});\n                let handle = {table}.insert({name}Instance {{ value, events: {name}Events::default() }});\n                // SAFETY: the header's contract: `out` is valid for one handle.\n                unsafe {{ ::rustnative_interop::runtime::write(out, handle) }}\n            }})\n        }}\n",
        symbol(idl, service, "new"),
        params.join(", "),
        rust_prologue(&service.constructor),
        arguments.join(", ")
    );
    // Free.
    let _ = writeln!(
        out,
        "{attributes}\n        pub extern \"C\" fn {}(this: u64) -> i32 {{\n            ::rustnative_interop::runtime::guard(|| {table}.remove(this))\n        }}\n",
        symbol(idl, service, "free")
    );
    // Methods.
    for method in &service.methods {
        let mut params = vec!["this: u64".to_owned()];
        params.extend(
            method.params.iter().map(|param| format!("{}: {}", param.name, rust_ffi(param.ty))),
        );
        if let Some(ty) = method.returns {
            params.push(format!("out: {}", rust_ffi_out(ty)));
        }
        let affinity = match method.threading {
            Threading::Owner => "Owner",
            Threading::Any => "Any",
        };
        let mut arguments: Vec<String> =
            method.params.iter().map(|param| param.name.clone()).collect();
        if method.receiver == Receiver::Exclusive {
            arguments.push("events".to_owned());
        }
        let call = format!(
            "{table}.with(this, ::rustnative_interop::runtime::Affinity::{affinity}, |instance| {{\n                    let {name}Instance {{ value, events }} = instance;\n                    let _ = &events;\n                    {name}::{}(value, {})\n                }})?",
            method.name,
            arguments.join(", ")
        );
        let finish = match method.returns {
            None => format!("                {call};\n                Ok(())"),
            Some(ty) => {
                let convert = match ty {
                    Type::Bool => "u8::from(result)",
                    Type::String => "::rustnative_interop::runtime::owned_string(&result)",
                    _ => "result",
                };
                format!(
                    "                let result = {call};\n                // SAFETY: the header's contract: `out` is valid for one result.\n                unsafe {{ ::rustnative_interop::runtime::write(out, {convert}) }}"
                )
            }
        };
        let _ = writeln!(
            out,
            "{attributes}\n        pub unsafe extern \"C\" fn {}({}) -> i32 {{\n            ::rustnative_interop::runtime::guard(|| {{\n{}{finish}\n            }})\n        }}\n",
            symbol(idl, service, &method.name),
            params.join(", "),
            rust_prologue(&method.params)
        );
    }
    // Event registration.
    for event in &service.events {
        let _ = writeln!(
            out,
            "{attributes}\n        pub extern \"C\" fn {}(this: u64, callback: ::core::option::Option<{name}{}Fn>, context: *mut ::core::ffi::c_void) -> i32 {{\n            ::rustnative_interop::runtime::guard(|| {{\n                let callback = callback.ok_or_else(|| {{\n                    ::rustnative_interop::runtime::fail(::rustnative_interop::runtime::status::INVALID_ARGUMENT, \"the callback is null\")\n                }})?;\n                let context = context as usize;\n                {table}.with(this, ::rustnative_interop::runtime::Affinity::Owner, |instance| {{\n                    instance.events.{}.push((callback, context));\n                }})\n            }})\n        }}\n",
            symbol(idl, service, &format!("on_{}", event.name)),
            pascal(&event.name),
            event.name
        );
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::idl::parse_idl;

    const COUNTER: &str = "library counter;\nservice Counter {\n    new(start: u32);\n    fn increment(&mut self) -> u32;\n    fn name(&self) -> string;\n    fn rename(&mut self, name: string);\n    event changed(value: u32);\n}\n";

    #[test]
    fn the_c_header_declares_the_abi() {
        let header = c(&parse_idl(COUNTER).unwrap());
        assert!(
            header.contains("int32_t counter_Counter_new(uint32_t start, counter_Counter* out);"),
            "{header}"
        );
        assert!(
            header.contains("int32_t counter_Counter_name(counter_Counter self, char** out);"),
            "{header}"
        );
        assert!(
            header.contains(
                "typedef void (*counter_Counter_changed_fn)(void* context, uint32_t value);"
            ),
            "{header}"
        );
        assert!(header.contains("void counter_string_free(char* value);"), "{header}");
    }

    #[test]
    fn csharp_wraps_each_service() {
        let bindings = csharp(&parse_idl(COUNTER).unwrap());
        assert!(bindings.contains("public sealed class Counter : IDisposable"), "{bindings}");
        assert!(bindings.contains("public uint Increment()"), "{bindings}");
        assert!(bindings.contains("public void OnChanged(Action<uint> handler)"), "{bindings}");
    }

    #[test]
    fn rust_writes_a_trait_and_an_export_macro() {
        let shims = rust(&parse_idl(COUNTER).unwrap());
        assert!(shims.contains("pub trait Counter: 'static {"), "{shims}");
        assert!(shims.contains("runtime::OwnerTable<CounterInstance<$counter>>"), "{shims}");
        assert!(
            shims.contains("fn increment(&mut self, events: &CounterEvents) -> u32;"),
            "{shims}"
        );
        assert!(shims.contains("macro_rules! export_counter"), "{shims}");
    }
}
