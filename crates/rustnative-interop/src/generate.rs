const fn c_type(ty: Type) -> &'static str {
    match ty {
        Type::Bool => "uint8_t",
        Type::I32 => "int32_t",
        Type::U32 => "uint32_t",
        Type::I64 => "int64_t",
        Type::U64 => "uint64_t",
        Type::F64 => "double",
        Type::String => "const char*",
    }
}

const fn c_out(ty: Type) -> &'static str {
    match ty {
        Type::String => "char**",
        Type::Bool => "uint8_t*",
        Type::I32 => "int32_t*",
        Type::U32 => "uint32_t*",
        Type::I64 => "int64_t*",
        Type::U64 => "uint64_t*",
        Type::F64 => "double*",
    }
}

fn c_params(params: &[Param]) -> Vec<String> {
    params.iter().map(|param| format!("{} {}", c_type(param.ty), param.name)).collect()
}

fn c_doc(out: &mut String, doc: &[String], indent: &str) {
    for line in doc {
        let _ = writeln!(out, "{indent}/* {line} */");
    }
}

/// The C header.
#[must_use]
pub fn c(idl: &Idl) -> String {
    let library = &idl.library;
    let guard = format!("{}_H", library.to_ascii_uppercase());
    let upper = library.to_ascii_uppercase();
    let mut out = String::new();
    let _ =
        writeln!(out, "/* Generated by rustnative-interop from `{library}.ril`. Do not edit. */");
    let _ = writeln!(out, "#ifndef {guard}\n#define {guard}\n\n#include <stdint.h>\n");
    let _ = writeln!(out, "#ifdef __cplusplus\nextern \"C\" {{\n#endif\n");
    for (name, value) in [
        ("OK", 0),
        ("PANICKED", 1),
        ("WRONG_THREAD", 2),
        ("INVALID_HANDLE", 3),
        ("INVALID_ARGUMENT", 4),
        ("BUSY", 5),
    ] {
        let _ = writeln!(out, "#define {upper}_{name} {value}");
    }
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "/* This thread's last failure message; valid until its next failing call. */"
    );
    let _ = writeln!(out, "const char* {library}_last_error(void);");
    let _ = writeln!(out, "/* Frees a string the library returned. */");
    let _ = writeln!(out, "void {library}_string_free(char* value);\n");
    for service in &idl.services {
        c_doc(&mut out, &service.doc, "");
        let handle = format!("{library}_{}", service.name);
        let _ = writeln!(out, "typedef uint64_t {handle};\n");
        let mut params = c_params(&service.constructor);
        params.push(format!("{handle}* out"));
        let _ = writeln!(out, "int32_t {}({});", symbol(idl, service, "new"), params.join(", "));
        let _ = writeln!(out, "int32_t {}({handle} self);", symbol(idl, service, "free"));
        for method in &service.methods {
            c_doc(&mut out, &method.doc, "");
            let mut params = vec![format!("{handle} self")];
            params.extend(c_params(&method.params));
            if let Some(ty) = method.returns {
                params.push(format!("{} out", c_out(ty)));
            }
            let threading = match method.threading {
                Threading::Owner => "owner thread",
                Threading::Any => "any thread",
            };
            let _ = writeln!(out, "/* [{threading}] */");
            let _ = writeln!(
                out,
                "int32_t {}({});",
                symbol(idl, service, &method.name),
                params.join(", ")
            );
        }
        for event in &service.events {
            c_doc(&mut out, &event.doc, "");
            let mut params = vec!["void* context".to_owned()];
            params.extend(c_params(&event.params));
            let callback = format!("{}_fn", symbol(idl, service, &event.name));
            let _ = writeln!(out, "typedef void (*{callback})({});", params.join(", "));
            let _ = writeln!(
                out,
                "int32_t {}({handle} self, {callback} callback, void* context);",
                symbol(idl, service, &format!("on_{}", event.name))
            );
        }
        let _ = writeln!(out);
    }
    let _ = writeln!(out, "#ifdef __cplusplus\n}}\n#endif\n\n#endif");
    out
}

