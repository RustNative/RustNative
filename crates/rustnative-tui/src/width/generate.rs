//! Regenerates `table.rs` from the Unicode Character Database.
//!
//! ```text
//! RUSTNATIVE_UCD_DIR=<folder with EastAsianWidth.txt, emoji-data.txt,
//!   DerivedGeneralCategory.txt> cargo test -p rustnative-tui -- --ignored regenerate
//! ```
//!
//! The files are Unicode 17.0.0's, the version `unicode-segmentation`'s
//! grapheme tables use, from `https://www.unicode.org/Public/17.0.0/ucd/`.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use super::Class;

fn ranges(text: &str) -> Vec<(u32, u32, String)> {
    text.lines()
        .filter_map(|line| {
            let line = line.split('#').next()?.trim();
            let (range, value) = line.split_once(';')?;
            let (first, last) = match range.trim().split_once("..") {
                Some((first, last)) => (first, last),
                None => (range.trim(), range.trim()),
            };
            Some((
                u32::from_str_radix(first, 16).ok()?,
                u32::from_str_radix(last, 16).ok()?,
                value.trim().to_owned(),
            ))
        })
        .collect()
}

fn put(class: &mut BTreeMap<u32, Class>, first: u32, last: u32, value: Class) {
    for code in first..=last {
        class.insert(code, value);
    }
}

#[test]
#[ignore = "regenerates the vendored table from the UCD files named by RUSTNATIVE_UCD_DIR"]
fn regenerate() {
    // CI runs the ignored tests too; without the UCD files there is nothing
    // to regenerate from.
    let Some(dir) = std::env::var_os("RUSTNATIVE_UCD_DIR").map(std::path::PathBuf::from) else {
        println!("skipped: RUSTNATIVE_UCD_DIR is not set");
        return;
    };
    let read = |name: &str| std::fs::read_to_string(dir.join(name)).expect(name);
    let east_asian = read("EastAsianWidth.txt");
    let emoji = read("emoji-data.txt");
    let categories = read("DerivedGeneralCategory.txt");
    assert!(east_asian.starts_with("# EastAsianWidth-17.0.0"), "the table is Unicode 17.0's");

    let mut class: BTreeMap<u32, Class> = BTreeMap::new();
    // The file's stated defaults for unlisted code points in the ideograph
    // blocks and planes, beneath what it lists.
    for (first, last) in [
        (0x3400, 0x4DBF),
        (0x4E00, 0x9FFF),
        (0xF900, 0xFAFF),
        (0x2_0000, 0x2_FFFD),
        (0x3_0000, 0x3_FFFD),
    ] {
        put(&mut class, first, last, Class::Wide);
    }
    for (first, last, value) in ranges(&east_asian) {
        match value.as_str() {
            "W" | "F" => put(&mut class, first, last, Class::Wide),
            "A" => put(&mut class, first, last, Class::Ambiguous),
            _ => {
                for code in first..=last {
                    class.remove(&code);
                }
            }
        }
    }
    for (first, last, value) in ranges(&emoji) {
        match value.as_str() {
            "Emoji_Presentation" => put(&mut class, first, last, Class::Wide),
            "Extended_Pictographic" => {
                for code in first..=last {
                    class.entry(code).or_insert(Class::TextEmoji);
                }
            }
            _ => {}
        }
    }
    for (first, last, value) in ranges(&categories) {
        if matches!(value.as_str(), "Mn" | "Me" | "Cf" | "Cc" | "Zl" | "Zp") {
            put(&mut class, first, last, Class::Zero);
        }
    }
    // Hangul jamo vowels and trailing consonants join the syllable before
    // them; the soft hyphen is shown where a line breaks at it, and counts
    // one column as `wcwidth` does.
    put(&mut class, 0x1160, 0x11FF, Class::Zero);
    put(&mut class, 0xD7B0, 0xD7FF, Class::Zero);
    class.remove(&0x00AD);

    let mut merged: Vec<(u32, u32, Class)> = Vec::new();
    for (code, value) in class {
        match merged.last_mut() {
            Some(last) if last.1 + 1 == code && last.2 == value => last.1 = code,
            _ => merged.push((code, code, value)),
        }
    }
    let mut out = String::from(
        "//! Generated by `width::generate::regenerate` from Unicode 17.0.0's\n\
         //! EastAsianWidth.txt, emoji-data.txt, and DerivedGeneralCategory.txt.\n\
         //! Do not edit by hand.\n\n\
         use super::Class::{self, Ambiguous, TextEmoji, Wide, Zero};\n\n\
         /// Every code point whose class is not narrow, as sorted inclusive ranges.\n\
         #[rustfmt::skip]\n\
         pub(super) static RANGES: &[(u32, u32, Class)] = &[\n",
    );
    for (first, last, value) in &merged {
        let name = match value {
            Class::Zero => "Zero",
            Class::Wide => "Wide",
            Class::Ambiguous => "Ambiguous",
            Class::TextEmoji => "TextEmoji",
            Class::Narrow => unreachable!("narrow is never stored"),
        };
        let _ = writeln!(out, "    (0x{first:05X}, 0x{last:05X}, {name}),");
    }
    out.push_str("];\n");
    let target = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src/width/table.rs");
    std::fs::write(&target, out).expect("write the table");
    eprintln!("wrote {} ranges to {}", merged.len(), target.display());
}
